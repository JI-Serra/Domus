import { colorTokenNames, colors } from './colors.ts';
import type { ColorTheme } from './colors.ts';
import {
  breakpoints,
  focusRing,
  layout,
  motion,
  radius,
  shadow,
  spacingUnit,
  touch,
} from './layout.ts';
import {
  fontFamilySans,
  gateTypeScale,
  typeRoles,
  typeScale,
} from './typography.ts';
import type { TypeStyle } from './typography.ts';

const rem = (px: number): string => `${px / 16}rem`;
const px = (value: number): string => `${value}px`;

const indent = (lines: readonly string[], depth: number): string[] =>
  lines.map((line) => `${'  '.repeat(depth)}${line}`);

function colorDeclarations(theme: ColorTheme): string[] {
  return colorTokenNames.map((name) => `--color-${name}: ${theme[name]};`);
}

function typeDeclarations(
  scale: Record<(typeof typeRoles)[number], TypeStyle>,
): string[] {
  return typeRoles.flatMap((role) => {
    const style = scale[role];
    return [
      `--text-${role}: ${rem(style.fontSize)};`,
      `--text-${role}--line-height: ${rem(style.lineHeight)};`,
      `--text-${role}--font-weight: ${style.fontWeight};`,
    ];
  });
}

function block(
  selector: string,
  declarations: readonly string[],
  depth = 0,
): string[] {
  return [
    ...indent([`${selector} {`], depth),
    ...indent(declarations, depth + 1),
    ...indent(['}'], depth),
  ];
}

/**
 * Builds the Tailwind v4 stylesheet for the web app from the typed tokens. The output is committed as
 * `apps/web/src/styles/tokens.generated.css`; a test fails if the file drifts from this function.
 *
 * Theme switching: `data-theme="light|dark"` on `<html>` is the manual override; without it the OS preference
 * (`prefers-color-scheme`) applies. `data-mode="gate"` turns on "modo garita" (bigger type and targets, high
 * contrast) and combines with either theme.
 */
export function generateTokensCss(): string {
  const themeDeclarations = [
    `--font-sans: var(--font-inter, '${fontFamilySans[0]}'), ${fontFamilySans
      .slice(1)
      .map((family) => (family.includes(' ') ? `"${family}"` : family))
      .join(', ')};`,
    `--spacing: ${px(spacingUnit)};`,
    ...Object.entries(breakpoints).map(
      ([name, value]) => `--breakpoint-${name}: ${px(value)};`,
    ),
    ...Object.entries(radius).map(
      ([name, value]) => `--radius-${name}: ${px(value)};`,
    ),
    `--shadow-modal: ${shadow.modal};`,
    `--container-content: ${px(layout.contentMaxWidth)};`,
    `--container-wide: ${px(layout.contentWideMaxWidth)};`,
    `--touch-min: ${px(touch.min)};`,
    `--touch-garita: ${px(touch.garita)};`,
    `--touch-primary-action: ${px(touch.primaryAction)};`,
    `--sidebar-width: ${px(layout.sidebarWidth)};`,
    `--tab-bar-height: ${px(layout.tabBarHeight)};`,
    `--top-bar-height: ${px(layout.topBarHeight)};`,
    `--gutter-mobile: ${px(layout.gutterMobile)};`,
    `--gutter-desktop: ${px(layout.gutterDesktop)};`,
    `--card-padding: ${px(layout.cardPadding)};`,
    `--card-dense-padding: ${px(layout.cardDensePadding)};`,
    ...colorDeclarations(colors.light),
    ...typeDeclarations(typeScale),
  ];

  const baseDeclarations = [
    'color-scheme: light;',
    `--control-height: var(--touch-min);`,
    `--ring-width: ${px(focusRing.default)};`,
    `--duration-ui: ${motion.maxTransitionMs}ms;`,
  ];

  const darkDeclarations = [
    'color-scheme: dark;',
    ...colorDeclarations(colors.dark),
  ];
  const gateDeclarations = [
    `--control-height: var(--touch-garita);`,
    `--ring-width: ${px(focusRing.gate)};`,
    ...colorDeclarations(colors['gate-light']),
    ...typeDeclarations(gateTypeScale),
  ];
  const gateDarkDeclarations = [
    'color-scheme: dark;',
    ...colorDeclarations(colors['gate-dark']),
  ];

  const lines: string[] = [
    '/* GENERATED by packages/ui-tokens (generateTokensCss). Do not edit by hand: run `pnpm gen:tokens`. */',
    '',
    '@theme static {',
    ...indent(themeDeclarations, 1),
    '}',
    '',
    ...block(':root', baseDeclarations),
    '',
    '@media (prefers-color-scheme: dark) {',
    ...block(":root:not([data-theme='light'])", darkDeclarations, 1),
    '}',
    '',
    ...block(":root[data-theme='dark']", darkDeclarations),
    '',
    ...block(":root[data-mode='gate']", gateDeclarations),
    '',
    '@media (prefers-color-scheme: dark) {',
    ...block(
      ":root[data-mode='gate']:not([data-theme='light'])",
      gateDarkDeclarations,
      1,
    ),
    '}',
    '',
    ...block(
      ":root[data-mode='gate'][data-theme='dark']",
      gateDarkDeclarations,
    ),
    '',
  ];

  return lines.join('\n');
}
