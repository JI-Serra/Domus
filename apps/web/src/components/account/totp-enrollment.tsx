'use client';

import { useTranslations } from 'next-intl';
import { useActionState, useState, useTransition } from 'react';
import {
  cancelTotpEnrollmentAction,
  startTotpEnrollmentAction,
  verifyTotpEnrollmentAction,
} from '@/app/(account)/account/security/actions';
import { AuthNotice } from '@/components/auth/auth-notice';
import {
  MfaCodeField,
  useCodeFormError,
} from '@/components/auth/mfa-code-field';
import { Button } from '@/components/ui/button';
import { Field, Input } from '@/components/ui/field';
import { INITIAL_CODE_STATE } from '@/lib/auth/mfa-state';
import type { EnrollmentStart } from '@/lib/auth/mfa-state';

type Started = Extract<EnrollmentStart, { ok: true }>;

function VerifyStep({
  started,
  next,
  onCancel,
}: {
  started: Started;
  next: string;
  onCancel: () => void;
}) {
  const t = useTranslations('account.security.mfa');
  const [state, action, pending] = useActionState(
    verifyTotpEnrollmentAction,
    INITIAL_CODE_STATE,
  );
  const formError = useCodeFormError(state);

  if (state.status === 'done')
    return <AuthNotice tone="success">{t('enrolled')}</AuthNotice>;

  return (
    <form action={action} noValidate className="flex flex-col gap-5">
      {formError ? <AuthNotice tone="error">{formError}</AuthNotice> : null}
      <input type="hidden" name="factorId" value={started.factorId} />
      <input type="hidden" name="next" value={next} />
      <div className="flex flex-col gap-5 sm:flex-row sm:items-start">
        {/* The QR is an SVG data URI generated by the auth server: not an optimizable image. */}
        {/* eslint-disable-next-line @next/next/no-img-element */}
        <img
          src={started.qrCode}
          alt={t('qrAlt')}
          width={192}
          height={192}
          className="size-48 shrink-0 rounded-card-dense bg-white p-2"
        />
        <div className="flex min-w-0 flex-1 flex-col gap-5">
          <Field
            label={t('secretLabel')}
            info={{ label: t('secretInfoLabel'), text: t('secretInfo') }}
          >
            <Input
              readOnly
              value={started.secret}
              spellCheck={false}
              className="tnum font-mono"
            />
          </Field>
          <MfaCodeField state={state} autoFocus />
        </div>
      </div>
      <div className="flex flex-wrap gap-3">
        <Button type="submit" disabled={pending}>
          {pending ? t('verifying') : t('verify')}
        </Button>
        <Button variant="secondary" onClick={onCancel} disabled={pending}>
          {t('cancel')}
        </Button>
      </div>
    </form>
  );
}

/**
 * Enrolls an authenticator app (TOTP): shows the QR and the manual key, then verifies the first code. Until that
 * code is verified the factor does not count; abandoning the flow discards it.
 */
export function TotpEnrollment({
  hasFactor,
  next,
}: {
  hasFactor: boolean;
  /** Validated same-origin path to continue to after enrolling, or an empty string. */
  next: string;
}) {
  const t = useTranslations('account.security.mfa');
  const errors = useTranslations('auth.errors');
  const [started, setStarted] = useState<Started | null>(null);
  const [startError, setStartError] = useState<string | null>(null);
  const [starting, startTransition] = useTransition();

  const start = () =>
    startTransition(async () => {
      const result = await startTotpEnrollmentAction();
      if (result.ok) {
        setStartError(null);
        setStarted(result);
      } else setStartError(errors(result.error));
    });

  const cancel = () => {
    const factorId = started?.factorId;
    setStarted(null);
    if (factorId) void cancelTotpEnrollmentAction(factorId);
  };

  if (started)
    return <VerifyStep started={started} next={next} onCancel={cancel} />;

  return (
    <div className="flex flex-col gap-4">
      {startError ? <AuthNotice tone="error">{startError}</AuthNotice> : null}
      <div>
        <Button
          variant={hasFactor ? 'secondary' : 'primary'}
          onClick={start}
          disabled={starting}
        >
          {starting
            ? t('starting')
            : hasFactor
              ? t('startAnother')
              : t('start')}
        </Button>
      </div>
    </div>
  );
}
